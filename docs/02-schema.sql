-- ============================================================
-- PHASE 2 — stock
-- ============================================================

CREATE TABLE scale_models (
    id                  uuid        PRIMARY KEY,
    name                text        NOT NULL,
    size_band           size_band   NOT NULL,
    description         text,
    low_stock_threshold int,                       -- NULL = use app_settings global
    is_active           boolean     NOT NULL DEFAULT true,
    is_deleted          boolean     NOT NULL DEFAULT false,
    created_at          timestamptz NOT NULL DEFAULT now(),
    created_by          uuid        NOT NULL,
    modified_at         timestamptz NOT NULL DEFAULT now(),
    modified_by         uuid        NOT NULL
);

-- Uniqueness must ignore soft-deleted rows. A plain UNIQUE would let a
-- soft-deleted model reserve its name forever, so re-creating a model
-- deleted by mistake would fail with a constraint violation the UI cannot
-- explain. Same reasoning applies to serials below.
CREATE UNIQUE INDEX uq_scale_models_name
    ON scale_models (name) WHERE NOT is_deleted;

CREATE TABLE goods_in_batches (
    id            uuid        PRIMARY KEY,
    reference     text,
    supplier_name text        NOT NULL DEFAULT 'Dibal',
    received_date date        NOT NULL,
    notes         text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    created_by    uuid        NOT NULL
);

CREATE TABLE stock_units (
    id                  uuid         PRIMARY KEY,
    model_id            uuid         NOT NULL REFERENCES scale_models(id),
    serial_no           text         NOT NULL,
    status              stock_status NOT NULL DEFAULT 'InStock',
    goods_in_batch_id   uuid         REFERENCES goods_in_batches(id),
    received_date       date         NOT NULL,
    current_delivery_id uuid,                      -- FK added after deliveries exists
    notes               text,
    is_deleted          boolean      NOT NULL DEFAULT false,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    created_by          uuid         NOT NULL,
    modified_at         timestamptz  NOT NULL DEFAULT now(),
    modified_by         uuid         NOT NULL,

    -- Referenced by the composite FK on delivery_lines, which keeps that
    -- table's denormalised model_id honest. Redundant against the PK, but an
    -- FK target must be a full (non-partial) unique constraint.
    CONSTRAINT uq_stock_id_model UNIQUE (id, model_id)
);

-- Serial is unique PER MODEL, not globally. Serial lookup may return
-- multiple rows across models; the UI must show a result list.
--
-- Partial on is_deleted: a soft-deleted unit must not reserve its serial.
-- Re-receiving SN-1042 after a mis-keyed unit was soft-deleted is normal.
CREATE UNIQUE INDEX uq_stock_model_serial
    ON stock_units (model_id, serial_no) WHERE NOT is_deleted;

CREATE INDEX ix_stock_status      ON stock_units (status) WHERE NOT is_deleted;
CREATE INDEX ix_stock_model       ON stock_units (model_id, status);
CREATE INDEX ix_stock_serial_trgm ON stock_units USING gin (serial_no gin_trgm_ops);
CREATE INDEX ix_stock_delivery    ON stock_units (current_delivery_id);

-- Keyset pagination needs a stable total ordering (see 01-architecture.md).
-- deliveries has ix_deliveries_date for the same purpose.
CREATE INDEX ix_stock_keyset ON stock_units (created_at DESC, id DESC)
    WHERE NOT is_deleted;

-- APPEND-ONLY. Never UPDATE or DELETE. Corrections are compensating rows.
CREATE TABLE stock_movements (
    id                bigserial     PRIMARY KEY,
    unit_id           uuid          NOT NULL REFERENCES stock_units(id),
    movement_type     movement_type NOT NULL,
    from_status       stock_status,
    to_status         stock_status  NOT NULL,
    delivery_id       uuid,
    goods_in_batch_id uuid          REFERENCES goods_in_batches(id),
    reason            text,
    occurred_at       timestamptz   NOT NULL DEFAULT now(),
    performed_by      uuid          NOT NULL
);

CREATE INDEX ix_movements_unit ON stock_movements (unit_id, occurred_at DESC);
CREATE INDEX ix_movements_delivery ON stock_movements (delivery_id);


-- ============================================================
-- PHASE 3 — deliveries
-- ============================================================

CREATE TABLE deliveries (
    id                  uuid            PRIMARY KEY,
    reference_no        text            NOT NULL UNIQUE,
    client_id           uuid            NOT NULL REFERENCES clients(id),
    status              delivery_status NOT NULL DEFAULT 'Draft',
    purchase_date       date,

    -- Frozen copy of the client's details at confirmation time.
    -- Documents render from this, never from the live client row.
    client_snapshot     jsonb,

    default_warranty_end  date,
    default_support_start date,
    default_support_end   date,

    notes               text,
    confirmed_at        timestamptz,
    confirmed_by        uuid,
    cancelled_at        timestamptz,
    cancelled_by        uuid,
    cancellation_reason text,
    is_deleted          boolean         NOT NULL DEFAULT false,
    created_at          timestamptz     NOT NULL DEFAULT now(),
    created_by          uuid            NOT NULL,
    modified_at         timestamptz     NOT NULL DEFAULT now(),
    modified_by         uuid            NOT NULL,

    -- Cancelled is permitted without a snapshot because a Draft may be
    -- cancelled. Hard-deleting a delivery is forbidden (CLAUDE.md invariant 2),
    -- so cancellation is the only disposal route for an abandoned draft — and
    -- a draft never had a snapshot to freeze.
    CONSTRAINT ck_confirmed_has_snapshot
        CHECK (status IN ('Draft', 'Cancelled') OR client_snapshot IS NOT NULL)
);

CREATE INDEX ix_deliveries_client ON deliveries (client_id, purchase_date DESC);
CREATE INDEX ix_deliveries_status ON deliveries (status) WHERE NOT is_deleted;
CREATE INDEX ix_deliveries_date   ON deliveries (purchase_date DESC, id DESC);

ALTER TABLE stock_units
    ADD CONSTRAINT fk_stock_delivery
    FOREIGN KEY (current_delivery_id) REFERENCES deliveries(id);

-- Declared here for the same phase-ordering reason: stock_movements is created
-- in Phase 2, before deliveries exists.
ALTER TABLE stock_movements
    ADD CONSTRAINT fk_movements_delivery
    FOREIGN KEY (delivery_id) REFERENCES deliveries(id);

CREATE TABLE delivery_lines (
    id            uuid PRIMARY KEY,
    delivery_id   uuid NOT NULL REFERENCES deliveries(id),
    stock_unit_id uuid NOT NULL REFERENCES stock_units(id),
    model_id      uuid NOT NULL REFERENCES scale_models(id),  -- denormalised for reporting

    -- Defaulted from the delivery header, editable per line.
    warranty_end  date,
    support_start date,
    support_end   date,

    -- Support Valid/Expired is COMPUTED from support_end. Never stored.

    CONSTRAINT uq_line_delivery_unit UNIQUE (delivery_id, stock_unit_id),

    -- model_id is denormalised for reporting, so it can drift from the unit's
    -- actual model. This composite FK makes drift impossible at the database
    -- level rather than relying on the delivery builder to get it right.
    CONSTRAINT fk_line_unit_model
        FOREIGN KEY (stock_unit_id, model_id) REFERENCES stock_units (id, model_id)
);

CREATE INDEX ix_lines_delivery ON delivery_lines (delivery_id);
CREATE INDEX ix_lines_unit     ON delivery_lines (stock_unit_id);
CREATE INDEX ix_lines_support  ON delivery_lines (support_end);   -- expiry alerts

-- A unit can only sit on one active delivery. Enforced by
-- stock_units.current_delivery_id + status inside the allocation transaction.

-- Renewals EXTEND delivery_lines.support_end and log history here.
-- Never overwrite history.
CREATE TABLE support_renewals (
    id               uuid        PRIMARY KEY,
    delivery_line_id uuid        NOT NULL REFERENCES delivery_lines(id),
    previous_end     date,
    new_end          date        NOT NULL,
    note             text,
    renewed_at       timestamptz NOT NULL DEFAULT now(),
    renewed_by       uuid        NOT NULL
);

CREATE INDEX ix_renewals_line ON support_renewals (delivery_line_id, renewed_at DESC);

-- Gapless-ish reference numbering. Claim with SELECT ... FOR UPDATE.
CREATE TABLE delivery_counters (
    year        int PRIMARY KEY,
    last_number int NOT NULL DEFAULT 0
);


