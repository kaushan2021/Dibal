CREATE TABLE outbox_messages (
    id              bigserial     PRIMARY KEY,
    message_type    text          NOT NULL,
    payload         jsonb         NOT NULL,
    status          outbox_status NOT NULL DEFAULT 'Pending',
    attempts        int           NOT NULL DEFAULT 0,
    next_attempt_at timestamptz   NOT NULL DEFAULT now(),
    last_error      text,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    sent_at         timestamptz
);

-- 'Failed' is in this index so the UI can list failures and offer a manual
-- resend. It is NOT a licence to auto-retry them: Failed is terminal after 5
-- attempts, so OutboxProcessor's claim query MUST also filter `attempts < 5`.
-- Without that, dead messages are re-claimed on every 30s poll forever.
CREATE INDEX ix_outbox_pending ON outbox_messages (status, next_attempt_at)
    WHERE status IN ('Pending', 'Failed');

CREATE TABLE email_log (
    id                bigserial   PRIMARY KEY,
    outbox_message_id bigint      REFERENCES outbox_messages(id),
    document_id       uuid        REFERENCES documents(id),
    to_address        text        NOT NULL,
    subject           text        NOT NULL,
    succeeded         boolean     NOT NULL,
    error             text,
    attempted_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_email_log_document ON email_log (document_id, attempted_at DESC);


-- ============================================================
-- PHASE 6 — dashboard aggregates
-- ============================================================

CREATE MATERIALIZED VIEW stock_levels AS
SELECT
    m.id            AS model_id,
    m.name          AS model_name,
    m.size_band,
    count(*) FILTER (WHERE u.status = 'InStock')   AS in_stock,
    count(*) FILTER (WHERE u.status = 'Allocated') AS allocated,
    count(*) FILTER (WHERE u.status = 'Delivered') AS delivered,
    coalesce(m.low_stock_threshold,
             (SELECT low_stock_threshold FROM app_settings WHERE id = 1)) AS threshold
FROM scale_models m
LEFT JOIN stock_units u ON u.model_id = m.id AND NOT u.is_deleted
WHERE NOT m.is_deleted
GROUP BY m.id, m.name, m.size_band, m.low_stock_threshold;

CREATE UNIQUE INDEX ix_stock_levels_model ON stock_levels (model_id);
